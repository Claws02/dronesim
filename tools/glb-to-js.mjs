#!/usr/bin/env node
/*
 * glb-to-js.mjs: wrap a .glb file in a small .js file so the guide can load it when opened
 * straight from disk (file://), where browsers block fetching .glb files.
 *
 * Usage:
 *   node tools/glb-to-js.mjs path/to/drone.glb [modelName] [--out models/drone.glb.js]
 *   node tools/glb-to-js.mjs path/to/drone.glb --list      # print part names + sizes (no output file)
 *
 * Then:
 *   1. add "models/<name>.glb.js" to GUIDE.settings.models in index.html
 *   2. use  model: "<name>"  in any assembly3d diagram
 *
 * No dependencies (Node 18+).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';

const args = process.argv.slice(2);
if (!args.length || args.includes('-h') || args.includes('--help')) {
  console.log('Usage: node tools/glb-to-js.mjs <file.glb> [modelName] [--out <file.js>] [--list]');
  process.exit(args.length ? 0 : 1);
}
const file = args[0];
const outIdx = args.indexOf('--out');
const out = outIdx > -1 ? args[outIdx + 1] : null;
const list = args.includes('--list');
const name = (args[1] && !args[1].startsWith('--') ? args[1] : basename(file).replace(/\.(glb|gltf)$/i, '')).replace(/[^\w-]+/g, '-');

const buf = readFileSync(file);
if (buf.readUInt32LE(0) !== 0x46546c67) { console.error(`${file} is not a binary glTF (.glb). Export as GLB (binary), not .gltf.`); process.exit(1); }

/* --- read the JSON chunk to report node names (helps choose "parts" names) --- */
const jsonLen = buf.readUInt32LE(12);
const gltf = JSON.parse(buf.slice(20, 20 + jsonLen).toString('utf8'));
const nodes = gltf.nodes || [];
const named = nodes.filter(n => n.name).map(n => n.name);
const dupes = named.filter((n, i) => named.indexOf(n) !== i);
const unnamed = nodes.length - named.length;
const exts = gltf.extensionsUsed || [];

console.log(`Model: ${file}  (${(buf.length / 1024).toFixed(0)} KB, ${nodes.length} nodes, ${named.length} named)`);
if (exts.includes('KHR_draco_mesh_compression')) console.warn('⚠ Uses Draco compression, which this player does not include. Re-export without Draco (Meshopt or no compression is fine).');
if (dupes.length) console.warn(`⚠ Duplicate node names (only the first of each is addressable): ${[...new Set(dupes)].slice(0, 15).join(', ')}`);
const mats = gltf.materials || [];
const white = mats.filter(m => { const pbr = m.pbrMetallicRoughness || {}; const c = pbr.baseColorFactor; return !pbr.baseColorTexture && (!c || (c[0] > 0.97 && c[1] > 0.97 && c[2] > 0.97)); }).map(m => m.name || '(unnamed)');
if (white.length) console.warn(`⚠ ${white.length} material(s) will render plain white (no colour and no texture): ${white.slice(0, 8).join(', ')}. Usually a texture got lost in export. Set a base colour in CAD/Blender if white isn't intended.`);
const nLights = ((gltf.extensions || {}).KHR_lights_punctual || {}).lights?.length || 0, nCams = (gltf.cameras || []).length;
if (nLights || nCams) console.warn(`ℹ Contains ${nLights} light(s) and ${nCams} camera(s) from the CAD/Blender scene. The player ignores them, but removing them in the export keeps the file clean.`);
if (buf.length > 8e6) console.warn(`⚠ ${(buf.length / 1e6).toFixed(1)} MB is heavy for a guide. Shrink it first (keeps part names): see "Shrinking a heavy model" in ASSEMBLY_ANIMATION_GUIDE.md.`);
if (unnamed) console.warn(`ℹ ${unnamed} unnamed nodes. Name the parts you want to animate in your CAD/Blender export.`);

if (list) {
  const childOf = new Map(); nodes.forEach((n, i) => (n.children || []).forEach(c => childOf.set(c, i)));
  const depth = i => { let d = 0; while (childOf.has(i)) { i = childOf.get(i); d++; } return d; };
  console.log('\nPart names (indent = nesting; animate a parent and its children move with it):');
  nodes.forEach((n, i) => { if (n.name) console.log('  ' + '  '.repeat(depth(i)) + n.name + (n.mesh != null ? '' : '  (group)')); });
  process.exit(0);
}

const target = out || join(dirname(file), name + '.glb.js');
mkdirSync(dirname(target), { recursive: true });
const js = `/* Offline model wrapper for ${basename(file)}, generated by tools/glb-to-js.mjs.\n   Add this file to GUIDE.settings.models and use  model: ${JSON.stringify(name)}  in assembly3d diagrams. */\n` +
  `(window.ASSEMBLY_MODELS = window.ASSEMBLY_MODELS || {})[${JSON.stringify(name)}] = "data:model/gltf-binary;base64,${buf.toString('base64')}";\n`;
writeFileSync(target, js);
console.log(`\n✓ Wrote ${target}  (model name: "${name}")`);
console.log(`  Next: add "${target.replace(/\\/g, '/')}" to GUIDE.settings.models, then use  model: "${name}"`);
